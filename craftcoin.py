def transfer_flow():
    global current_user, addr # Add addr to global scope
    load_addr() # Ensure we have the latest balances before attempting transfer
    print("--- Secure Transfer ---")
    username = input("Username: ").strip()
    password = input("Password: ").strip()
    hashed_pw = hash_password(password)

    if username in users and users[username]['password'] == hashed_pw:
        current_user = username
        # Assuming sender's balance is tied to the username directly in the 'addr' dict
        sender_account_key = username # Use username as the key for addr

        print(f"Logged in as {username}. Current Balance: {addr.get(sender_account_key, 0)}")

        s = input("Select address to transfer to: ").strip() # Recipient

        if s not in addr: # Check if recipient address exists
            print("Invalid recipient address.")
            return # Exit function if recipient is invalid

        if s == sender_account_key: # Prevent self-transfer
            print("Cannot transfer to yourself.")
            return

        yy = input("How much would you like to transfer?")
        try:
            transfer_amount = float(yy)
        except ValueError:
            print("Invalid amount. Please enter a number.")
            return

        if transfer_amount <= 0:
            print("Transfer amount must be positive.")
            return

        if addr.get(sender_account_key, 0) >= transfer_amount: # Check sender's balance against transfer amount
            addr[sender_account_key] -= transfer_amount
            addr[s] += transfer_amount
            blco() # Call blco to increment m, assuming it's the transaction counter
            led(f'Transaction {m}: {sender_account_key} sent {transfer_amount} Craftcoin to {s}')
            print("Transfer Successful!")
            save_addr() # NEW: Save balances after successful transfer
        else:
            print("Insufficient Funds")
    else:
        print("Authentication Failed.")


